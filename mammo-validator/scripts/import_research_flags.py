#!/usr/bin/env python3
"""
Import Research Flags into Mammo QA Workbench
=============================================

Reads `research_flagged_cases.csv` (generated by confident learning analysis 
in bestone_v3_cv_oof.ipynb), joins it with VinDr metadata (`vindr_detection_v1_folds.csv`)
and OOF predictions (`oof_predictions.csv`), and writes a new `lib/mock-data.ts`.

Every flagged patient receives ALL their available views (typically 4: R/L-CC + R/L-MLO).
Flagged image(s) carry the label-disagreement finding; the other views are loaded as
context with their real OOF model prediction.

Usage:
    python scripts/import_research_flags.py [path/to/research_flagged_cases.csv]

Output:
    mammo-validator/lib/mock-data.ts  -- overwrites the existing mock cases
"""

import pandas as pd
import os
import sys
from datetime import datetime
from pathlib import Path

# MAMMO_VALIDATOR = mammo-validator/ (this script lives in its scripts/ dir).
MAMMO_VALIDATOR = Path(__file__).resolve().parent.parent

FLAG_KINDS = {
    2: 'mass',       # Suspicious
    1: 'asymmetry',  # Benign-leaning is low-risk; not flagged much, keep simple
}

def resolve_csv(name: str):
    candidates = [
        MAMMO_VALIDATOR / name,
        Path.cwd() / name,
    ]
    return next((c for c in candidates if c.exists()), None)

def map_predicted_to_birads(pred_class: int, prob_suspicious: float) -> str:
    """Map model prediction (0=Normal, 1=Benign-leaning, 2=Suspicious) to BI-RADS grade."""
    if pred_class == 2:
        return '4C' if prob_suspicious < 0.9 else '5'
    elif pred_class == 1:
        return '3'
    else:
        return '1'

def map_true_to_birads(true_class: int) -> str:
    return {0: '1', 1: '3', 2: '4C'}.get(true_class, '1')

def generate_study_uid(index: int) -> str:
    return f"1.2.826.0.1.3680043.10.844.cl.{index + 1000}"

def build_grade_probabilities(pred_class: int, prob_normal: float, prob_benign: float, prob_suspicious: float) -> dict:
    probs = {
        '0': 0.0,
        '1': prob_normal,
        '2': prob_benign * 0.5,
        '3': prob_benign * 0.5,
        '4A': prob_suspicious * 0.2,
        '4B': prob_suspicious * 0.3,
        '4C': prob_suspicious * 0.5,
        '5': 0.0,
        '6': 0.0,
    }
    total = sum(probs.values())
    if total > 0:
        probs = {k: round(v / total, 4) for k, v in probs.items()}
    return probs

def build_case_ts(image_id, patient_id, laterality, view, index, birads_grade,
                  confidence, prob_normal, prob_benign, prob_suspicious,
                  findings, description) -> str:
    grade_probs = build_grade_probabilities(
        {'1': 0, '3': 1, '4C': 2, '5': 2}[birads_grade], prob_normal, prob_benign, prob_suspicious
    )
    prob_str = ",\n        ".join([f'"{k}": {v}' for k, v in grade_probs.items()])
    findings_ts = ",\n".join(
        f"""        {{
          id: "f-cl-{f['id']}",
          kind: "{f['kind']}",
          description: "{f['description']}",
          location: "{f['location']}",
          probability: {f['probability']:.4f}
        }}"""
        for f in findings
    )
    return f"""  {{
    imageId: "{image_id}",
    patient: {{ id: "{patient_id}", sex: "F", ageAtStudy: 55 }},
    study: {{
      studyInstanceUid: "{generate_study_uid(index)}",
      date: "2026-09-08",
      description: "{description}",
      accessionNumber: "CL-{image_id}"
    }},
    acquisition: {{ laterality: "{laterality}", view: "{view}", pixelSpacingMm: 0.07 }},
    image: {{
      type: "png",
      url: "/samples/cl/{image_id}",
      width: 1024,
      height: 1024,
      bitsAllocated: 8
    }},
    ai: {{
      biradsGrade: "{birads_grade}",
      confidence: {confidence:.4f},
      gradeProbabilities: {{
        {prob_str}
      }},
      findings: [
{findings_ts}
      ],
      model: "SwinV2 + FT-Transformer + Cross-Attention + CatBoost",
      modelVersion: "v1.0-cl",
      runAt: "{datetime.now().isoformat()}Z"
    }}
  }}"""

def main():
    if len(sys.argv) > 1:
        csv_path = Path(sys.argv[1])
        if not csv_path.is_absolute():
            csv_path = Path.cwd() / csv_path
        flagged_path = csv_path
    else:
        flagged_path = resolve_csv("research_flagged_cases.csv")
        if flagged_path is None:
            print("❌ Error: research_flagged_cases.csv not found.")
            print("   Please place it in mammo-validator/ or provide the path as an argument.")
            sys.exit(1)

    flags = pd.read_csv(flagged_path)
    print(f"📄 Loaded {len(flags)} flagged cases from {flagged_path}")

    vindr_path = resolve_csv("vindr_detection_v1_folds.csv")
    oof_path = resolve_csv("oof_predictions.csv")
    if vindr_path is None or oof_path is None:
        print("❌ Need vindr_detection_v1_folds.csv AND oof_predictions.csv in mammo-validator/.")
        sys.exit(1)

    vindr = pd.read_csv(vindr_path, low_memory=False)
    oof = pd.read_csv(oof_path)

    # Map image_id -> (patient_id, laterality, view) from VinDr metadata.
    meta = (vindr[['image_id', 'patient_id', 'laterality', 'view']]
            .drop_duplicates('image_id')
            .set_index('image_id'))

    # OOF model probabilities per image (context views).
    oof = oof.drop_duplicates('image_id').set_index('image_id')

    # Flagged rows keyed by image_id for lookup.
    flags_by_img = flags.set_index('image_id')

    flagged_patients = set(flags['patient_id'])
    pat_meta = meta[meta['patient_id'].isin(flagged_patients)]

    # Map patient -> list of (image_id, laterality, view), deterministic order.
    patients = {}
    for image_id, row in pat_meta.iterrows():
        patients.setdefault(row['patient_id'], []).append(
            (image_id, row['laterality'], row['view'])
        )
    for images in patients.values():
        images.sort(key=lambda t: (t[1], t[2]))  # L/R then CC/MLO

    # Deterministic: assign each patient's images with a per-patient index; emit in
    # patient_id order so grouping stays contiguous.
    ts_content = '''// GENERATED BY scripts/import_research_flags.py
// DO NOT EDIT MANUALLY — re-run this script to update from CSV
import type {
  AiFinding,
  AiPrediction,
  BiRadsGrade,
  StudyCase,
} from './types';
import { biradsAuditLabel } from './taxonomy';

/**
 * Research Flag Cases — Confident Learning False-Negative Candidates
 *
 * Patients flagged by Confident Learning (Cleanlab): high-confidence label
 * disagreements where the model predicts Suspicious but the original label
 * is Normal/Benign-leaning (self-confidence in the original label < 50%).
 *
 * Each flagged patient includes ALL their views for clinical context; the
 * flagged image(s) carry the label-disagreement finding.
 *
 * Source: bestone_v3_cv_oof.ipynb → research_flagged_cases.csv
 */

export const MOCK_CASES: StudyCase[] = [
'''

    cases_ts = []
    global_index = -1
    for patient_id in sorted(patients.keys()):
        for image_id, laterality, view in patients[patient_id]:
            global_index += 1
            oof_row = oof.loc[image_id] if image_id in oof.index else None
            prob_normal = float(oof_row['prob_normal']) if oof_row is not None else 0.1
            prob_benign = float(oof_row['prob_benign_leaning']) if oof_row is not None else 0.1
            prob_suspicious = float(oof_row['prob_suspicious']) if oof_row is not None else 0.1

            if image_id in flags_by_img.index:
                frow = flags_by_img.loc[image_id]
                pred_label = int(frow['model_predicted_label'])
                birads_grade = map_predicted_to_birads(pred_label, prob_suspicious)
                true_birads = map_true_to_birads(int(frow['true_label']))
                true_name = frow['true_label_name']
                pred_name = frow['model_predicted_name']
                self_conf = float(frow['self_confidence'])
                desc = (
                    f"Label Disagreement Flagged: Original label is {true_name} "
                    f"(BI-RADS {true_birads}), but our model predicts {pred_name} "
                    f"(BI-RADS {birads_grade}) with {prob_suspicious*100:.1f}% confidence. "
                    f"Model self-confidence in original label: {self_conf*100:.1f}%."
                )
                findings = [{
                    'id': image_id,
                    'kind': FLAG_KINDS.get(pred_label, 'mass'),
                    'description': desc,
                    'location': 'See full image scans',
                    'probability': prob_suspicious,
                }]
                confidence = prob_suspicious
                study_desc = "Confident Learning Disagreement Review"
            else:
                # Context view: real OOF prediction (argmax of 3-class probs), no finding.
                if oof_row is not None:
                    pred_label = 2 if prob_suspicious == max(prob_normal, prob_benign, prob_suspicious) \
                        else 1 if prob_benign >= prob_normal else 0
                else:
                    pred_label = 0
                birads_grade = map_predicted_to_birads(pred_label, prob_suspicious)
                findings = []
                confidence = max(prob_normal, prob_benign, prob_suspicious)
                study_desc = "Confident Learning Context View"

            cases_ts.append(build_case_ts(
                image_id, patient_id, laterality, view, global_index,
                birads_grade, confidence, prob_normal, prob_benign, prob_suspicious,
                findings, study_desc,
            ))

    ts_content += ",\n".join(cases_ts)

    ts_content += '''

];

/** Convenience: full AI audit string for a case (matches validation payloads). */
export function originalLabelFor(c: StudyCase): string {
  return biradsAuditLabel(c.ai.biradsGrade);
}

export function getMockCases(): StudyCase[] {
  return MOCK_CASES;
}
'''

    output_path = MAMMO_VALIDATOR / "lib" / "mock-data.ts"
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(ts_content)

    flagged_count = len(flags_by_img)
    print(f"✅ Generated {output_path}")
    print(f"   {len(cases_ts)} views across {len(patients)} patients "
          f"({flagged_count} flagged views)")
    print(f"\n📋 Next steps:")
    print(f"   Run 'npm run dev' in mammo-validator/ to start the workbench")
    print(f"   Doctors can review at http://localhost:3000")

if __name__ == "__main__":
    main()